export function getTranslatedOrgan(ruName, lang) {
  if (lang !== 'uz' || !ruName) return ruName;
  const lower = ruName.toLowerCase().trim();
  for (const [k, v] of Object.entries(organTranslations)) {
    if (lower.includes(k)) return v;
  }
  return ruName;
}
